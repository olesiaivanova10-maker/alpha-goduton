USER_PROMPT_TEMPLATE = """СОСТАВЬ ПЕРСОНАЛИЗИРОВАННЫЙ ИНСАЙТ ПО СТАНДАРТУ АЛЬФА-БАНКА:

[КОНТЕКСТ КОМПАНИИ]:
- Название: {company_name}
- Выручка: {revenue_billions:.1f} млрд ₽
- Отрасль: {okved_code} {okved_name}
- Продуктовый портфель в банке: {products_summary}
- ВЭД: {ved_summary}
- Роль читателя: {target_role}

{role_modifier}

[СОБЫТИЕ / НОВОСТЬ]:
- Заголовок: {news_title}
- Текст: {news_body}

[ЭКСПЕРТИЗА АЛЬФА-БАНКА (RAG)]:
{bank_context}

Сгенерируй ответ строго в формате JSON:
{{
  "fact_summary": "2-3 предложения чистых фактов",
  "why_it_matters": "Глубокое объяснение причинно-следственной связи с балансом и операциями клиента",
  "alfa_bank_position": {{
    "has_bank_report": true/false,
    "source_report_title": "Название отчета или null",
    "position_text": "Позиция аналитиков банка или маркированная гипотеза AI",
    "is_official_view": true/false
  }},
  "risks": [
    "Конкретный риск 1",
    "Конкретный риск 2"
  ],
  "opportunities": [
    "Конкретная возможность 1"
  ],
  "next_best_action": {{
    "action_type": "HEDGING | CREDIT | FACTORING | CONSULTATION | DEPOSIT",
    "title": "Название кнопки действия",
    "description": "Понятное обоснование шага для клиента",
    "bank_product_tag": "Продукт Альфа-Банка"
  }},
  "sources": ["Источник 1", "Источник 2"],
  "disclaimer": "Не является индивидуальной инвестиционной рекомендацией"
}}"""


def build_deepseek_insight_prompt(company: dict, news: dict, bank_data: dict, role: UserRole) -> Dict[str, str]:
    products = []
    if company.get("cl_product_loa"): products.append("Кредитные линии")
    if company.get("cl_product_lea"): products.append("Лизинг")
    if company.get("cl_product_dep"): products.append("Депозиты/овернайты")
    if company.get("cl_product_zpp"): products.append("Зарплатный проект")
    if company.get("factoring_mark"): products.append("Факторинг")
    if company.get("cl_product_gar"): products.append("Банковские гарантии")
    products_summary = ", ".join(products) if products else "Базовое РКО"

    ved_summary = f"Активный участник ВЭД (страны: {company.get('fts_country_name')})" if company.get("fts_flag") else "Внутренний рынок РФ"

    bank_context = f"Отчет: {bank_data.get('title', 'Отчет Центра макроисследований')}\nПозиция: {bank_data.get('text', '')}"

    return {
        "system": SYSTEM_PROMPT,
        "user": USER_PROMPT_TEMPLATE.format(
            company_name=company.get("display_name", "Клиент"),
            revenue_billions=company.get("revenue_company", 0) / 1e9,
            okved_code=company.get("mainokved_code", "00.00"),
            okved_name=company.get("mainokved_name", ""),
            products_summary=products_summary,
            ved_summary=ved_summary,
            target_role=role.value,
            role_modifier=ROLE_MODIFIERS.get(role, ""),
            news_title=news.get("title", ""),
            news_body=news.get("body", ""),
            bank_context=bank_context
        )
    }
